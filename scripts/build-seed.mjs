// Generates supabase/migrations/*_seed.sql from seed/*.json
import { readFileSync, writeFileSync } from 'node:fs';

const syl = JSON.parse(readFileSync(new URL('../seed/syllabus.json', import.meta.url)));
const paper = JSON.parse(readFileSync(new URL('../seed/ict-paper1.json', import.meta.url)));
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;

let sql = '-- Generated by scripts/build-seed.mjs — syllabus, exam dates and ICT Paper 1\n\n';
for (const e of syl.parentEmails) sql += `insert into public.parent_emails(email) values (${q(e)}) on conflict do nothing;\n`;
sql += '\n';
for (const s of syl.subjects) {
  sql += `insert into public.subjects (id,name,emoji,color,world_name,practice_marks,papers,exam_notes,sort,active,term) values (${q(s.id)},${q(s.name)},${q(s.emoji)},${q(s.color)},${q(s.world_name)},${s.practice_marks ?? 50},${j(s.papers)},${q(s.exam_notes)},${s.sort},${s.active === false ? 'false' : 'true'},${q(syl.term || 'Grade 6 · Term 1 · 2026-27')})
  on conflict (id) do update set name=excluded.name, emoji=excluded.emoji, color=excluded.color, world_name=excluded.world_name, practice_marks=excluded.practice_marks, papers=excluded.papers, exam_notes=excluded.exam_notes, sort=excluded.sort, term=excluded.term;\n`;
  s.topics.forEach(([code, name, weight, p], i) => {
    sql += `insert into public.topics (id,subject_id,code,name,paper,weight,sort) values (${q(`${s.id}-${code}`)},${q(s.id)},${q(code)},${q(name)},${q(p || 'Theory')},${weight},${i})
  on conflict (id) do update set name=excluded.name, paper=excluded.paper, weight=excluded.weight, sort=excluded.sort;\n`;
  });
  sql += '\n';
}
const SECRET = ['answer', 'markScheme', 'explanation'];
const pub = paper.questions.map((qq) => Object.fromEntries(Object.entries(qq).filter(([k]) => !SECRET.includes(k))));
const key = Object.fromEntries(paper.questions.map((qq) => [qq.id, { answer: qq.answer, markScheme: qq.markScheme || [], explanation: qq.explanation || '' }]));
sql += `insert into public.exams (id,subject_id,title,level,total_marks,duration_min,instructions,questions,source) values (${q(paper.id)},${q(paper.subject_id)},${q(paper.title)},${q(paper.level)},${paper.total_marks},${paper.duration_min},${q(paper.instructions)},${j(pub)},'seed') on conflict (id) do nothing;\n`;
sql += `insert into public.exam_keys (exam_id,key) values (${q(paper.id)},${j(key)}) on conflict (exam_id) do nothing;\n`;

writeFileSync(new URL('../supabase/migrations/20261101000100_seed.sql', import.meta.url), sql);
console.log('seed written', sql.length, 'chars');
